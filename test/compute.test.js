'use strict';
const assert = require('node:assert/strict');
const { choose, scale, micros, charge } = require('../src/compute');
const machine = (id, tier, hourly, extra = {}) => ({ id, tier, hourly, currency: 'USD', free_ram_mb: 4096, free_slots: 4, health: 'up', region: 'us', latency_ms: 50, ...extra });
const machines = [machine('mine', 'own', 0, {owner: 'alice'}), machine('home', 'home', 0.01), machine('dedicated', 'dedicated', 0.02, {latency_ms: 10}), machine('community', 'community', 0.001), machine('burst', 'partner', 1)];
for (const [strategy, expected] of [['automatic','mine'],['cheapest','mine'],['fastest','dedicated'],['private','mine'],['own','mine']]) assert.equal(choose({strategy, owner:'alice'}, machines).selected, expected);
assert.equal(choose({strategy:'own', owner:'bob'}, machines).selected, null);
assert.equal(choose({strategy:'private', owner:'bob'}, machines).selected, 'home');
assert.equal(choose({owner:'bob', public_egress:true}, machines).selected, 'dedicated');
assert.equal(choose({owner:'bob'}, machines.map(m => m.id === 'home' ? {...m,queue_ms:31000} : m)).selected, 'dedicated');
assert.equal(choose({owner:'bob'}, machines.map(m => m.id === 'home' ? {...m,health:'down'} : m)).selected, 'dedicated');
assert.equal(choose({owner:'bob',max_hourly:0.005}, machines).selected, 'community');
assert.equal(choose({strategy:'private'}, [machine('bad','community',0)]).selected, null);
assert.equal(choose({}, [machine('unpriced','dedicated',null)]).selected, null);
assert.equal(choose({region:'eu'}, machines).selected, null);
assert.equal(choose({gpu_mb:24000}, machines).selected, null);
assert.equal(choose({}, [machine('eur','home',0,{currency:'EUR'})]).selected, null);
const a=machine('a','dedicated',1,{state:'running',managed:true,sessions:0,idle_since:0});
assert.equal(scale({min_warm:1},[],[],{now:100}).actions[0].action,'provision');
assert.equal(scale({},[a],Array.from({length:5},()=>({created_at:0})),{now:40000}).actions[0].action,'provision');
assert.deepEqual(scale({},[a],[],{now:700000}).actions,[{action:'drain',id:'a',reason:'idle grace elapsed'}]);
assert.equal(scale({},[{...a,draining:true}],[],{now:700000}).actions[0].action,'release');
assert.equal(scale({},[{...a,draining:true,sessions:1}],[],{now:700000}).actions.length,0);
assert.equal(scale({min_warm:1},[a],[],{now:700000}).actions.length,0);
assert.equal(scale({min_warm:1},[{...a,state:'provisioning',health:'starting'}],[],{now:700000}).actions.length,0);
assert.equal(micros('1.000001'),1000001n);
assert.throws(()=>micros('NaN'));
assert.throws(()=>micros('-1'));
assert.equal(charge(micros('1'),1,3600),1000000n);
assert.equal(charge(micros('1'),3600000,1),1000000n);
console.log('compute strategies, hard constraints, scale up/down/drain and exact billing: passed');
